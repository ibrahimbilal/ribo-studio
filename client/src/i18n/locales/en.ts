type DeepStringify<T> = T extends string
  ? string
  : { [K in keyof T]: DeepStringify<T[K]> }

/** Shape of UI messages — values are plain strings in every locale. */
export type MessageTree = DeepStringify<typeof en>

/** Locale overlays may omit keys; runtime deep-merges onto English. */
export type MessageOverlay = DeepPartial<MessageTree>
